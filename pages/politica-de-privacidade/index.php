## 2. Quais dados coletamos

### 2.1 Dados que você nos fornece
- **Cadastro:** nome, e-mail, CPF, telefone, data de nascimento, gênero.
- **Endereço:** logradouro, número, complemento, bairro, cidade, estado, CEP.
- **Compras:** histórico de pedidos, itens, valores.
- **Comunicação:** mensagens que você envia ao suporte, avaliações de produtos.

### 2.2 Dados coletados automaticamente
- **Navegação:** páginas visitadas, produtos vistos, itens no carrinho, buscas.
- **Técnicos:** endereço IP, tipo de navegador, sistema operacional, dispositivo.
- **Cookies e identificadores:** conforme a seção 6.

### 2.3 Dados de pagamento
Os dados de cartão são processados **diretamente** pelo nosso orquestrador de
pagamentos (Malga) e pelas instituições financeiras. A Sportmoto **não
armazena o número completo do cartão** — retemos apenas informações não
sensíveis para referência do pedido, como a **bandeira e os últimos 4
dígitos**, em conformidade com as práticas de segurança do setor (PCI-DSS).

