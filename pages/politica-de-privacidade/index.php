## 7. Seus Direitos (art. 18 da LGPD)

Você tem direito a, a qualquer momento e mediante requisição:

- **Confirmar** a existência de tratamento dos seus dados;
- **Acessar** seus dados;
- **Corrigir** dados incompletos, inexatos ou desatualizados;
- **Anonimizar, bloquear ou eliminar** dados desnecessários ou tratados em
  desconformidade com a LGPD;
- **Portar** seus dados a outro fornecedor de serviço;
- **Eliminar** dados tratados com base no seu consentimento;
- Obter **informação** sobre com quem compartilhamos seus dados;
- **Revogar o consentimento** a qualquer momento.

Para exercer esses direitos, entre em contato pelo e-mail
**ecommerce@sportmoto.com.br**. Responderemos no prazo legal.

> 🔴 **REVISÃO JURÍDICA (advogado):** definir o fluxo operacional de atendimento
> às requisições (quem recebe, como valida a identidade do titular, prazo de
> resposta) — a LGPD exige um canal e um processo.

