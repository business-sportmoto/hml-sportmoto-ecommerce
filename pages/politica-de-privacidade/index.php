## 4. Com quem compartilhamos (Operadores e Terceiros)

Compartilhamos dados com prestadores que nos ajudam a operar, cada um tratando
apenas o necessário para sua função:

| Terceiro | Finalidade | Dados compartilhados |
|---|---|---|
| **Malga** | Processamento de pagamento | Dados de transação |
| **Bling** | Gestão de pedidos e emissão fiscal (ERP) | Dados de pedido e contato |
| **Mailgun** | Envio de e-mails transacionais | E-mail, nome |
| **Cloudflare** | CDN, segurança e hospedagem de mídia | Dados técnicos, IP |
| **Meta (Facebook/Instagram)** | Publicidade e medição | Dados hasheados (ver 4.1) |
| **Google (Ads/Analytics)** | Publicidade e medição | Dados hasheados (ver 4.1) |

### 4.1 Sobre o compartilhamento com Meta e Google
Quando você **consente** com marketing/analytics, compartilhamos dados de
eventos (por exemplo: compra, visualização de produto) com Meta e Google para
medição e publicidade. **Antes de qualquer envio, os dados pessoais (como
e-mail e telefone) são transformados de forma irreversível por criptografia
(hash SHA-256)** — não enviamos seus dados em formato legível. Você pode
recusar esse compartilhamento a qualquer momento pelo banner de cookies.

> 🔴 **REVISÃO JURÍDICA (advogado):** Meta e Google implicam **transferência
> internacional de dados** (art. 33 da LGPD), pois processam fora do Brasil.
> Incluir a cláusula de transferência internacional adequada e verificar as
> salvaguardas (cláusulas contratuais padrão dos fornecedores).

