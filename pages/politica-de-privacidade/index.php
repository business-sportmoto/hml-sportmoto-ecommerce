## 5. Por quanto tempo guardamos (Retenção)

- **Dados de conta:** enquanto sua conta existir, e por um período adicional
  após a inativação para cumprimento de obrigações legais.
- **Dados de pedido e fiscais:** pelo prazo exigido pela legislação fiscal
  brasileira.
- **Registros de consentimento:** mantidos como evidência do seu consentimento,
  mesmo após eventual retirada.
- **Dados de marketing:** até a retirada do seu consentimento.

Após os prazos aplicáveis, os dados são anonimizados ou eliminados com
segurança.

> 🔴 **REVISÃO JURÍDICA (advogado):** confirmar os prazos específicos
> (obrigações fiscais — geralmente 5 anos; prazos de prescrição aplicáveis).

