## 8. Segurança dos Dados

Adotamos medidas técnicas e organizacionais para proteger seus dados,
incluindo: criptografia em trânsito (HTTPS), controle de acesso, firewall de
aplicação (WAF), monitoramento de segurança e minimização de dados. Nenhum
sistema é totalmente imune a riscos, mas trabalhamos continuamente para
proteger suas informações.

---

## 9. Menores de Idade

Nossos serviços são destinados a maiores de 18 anos. Não coletamos
intencionalmente dados de menores de idade. Caso identifiquemos tal coleta sem
o consentimento adequado, tomaremos as medidas para eliminar os dados.

> 🔴 **REVISÃO JURÍDICA (advogado):** a LGPD (art. 14) tem regras específicas
> para dados de crianças e adolescentes. Confirmar a posição e o tratamento.

