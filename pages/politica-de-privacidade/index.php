## 6. Cookies e Tecnologias de Rastreamento

Usamos cookies em três categorias:

- **Necessários (sempre ativos):** essenciais para o funcionamento — login,
  carrinho, segurança. Não podem ser desativados.
- **Analytics (opcional):** medem como o site é usado, para melhorá-lo.
  Ativados **apenas com seu consentimento**.
- **Marketing (opcional):** permitem publicidade relevante e medição de
  campanhas (Meta, Google). Ativados **apenas com seu consentimento**.

Você gerencia suas escolhas pelo **banner de cookies** exibido no primeiro
acesso, e pode alterá-las a qualquer momento por meio das opções de cookies
disponíveis no site.

